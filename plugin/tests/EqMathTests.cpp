#include "EqMath.h"
#include "dsp/EqEffect.h"
#include "EqGraphMath.h"

#include <cassert>
#include <array>
#include <cmath>
#include <iostream>

int main()
{
    using namespace semantifx::eq;
    constexpr auto sampleRate = 48000.0;

    const auto neutral = peak (sampleRate, 1000.0, 1.0, 0.0);
    assert (std::abs (magnitudeDb (neutral, 1000.0, sampleRate)) < 1.0e-9);

    const auto boostedPeak = peak (sampleRate, 1000.0, 1.0, 6.0);
    assert (std::abs (magnitudeDb (boostedPeak, 1000.0, sampleRate) - 6.0) < 0.01);

    const auto low = lowShelf (sampleRate, 200.0, 2.0, 6.0);
    assert (magnitudeDb (low, 40.0, sampleRate) > 5.5);
    assert (std::abs (magnitudeDb (low, 10000.0, sampleRate)) < 0.1);

    const auto high = highShelf (sampleRate, 6000.0, 0.5, -6.0);
    assert (magnitudeDb (high, 16000.0, sampleRate) < -5.0);
    assert (std::abs (magnitudeDb (high, 200.0, sampleRate)) < 0.1);

    const auto clamped = peak (sampleRate, 100000.0, 1.0, 3.0);
    assert (std::isfinite (clamped.b0) && std::isfinite (clamped.a2));

    // Reference coefficients generated by dasp_pytorch.signal.biquad in float32.
    const auto close = [] (double actual, double expected) { return std::abs (actual - expected) < 2.0e-6; };
    assert (close (low.b0, 1.00237929821014));
    assert (close (low.b1, -1.98832476139069));
    assert (close (low.b2, 0.98690801858902));
    assert (close (low.a1, -1.98856472969055));
    assert (close (low.a2, 0.989047229290009));
    assert (close (boostedPeak.b0, 1.04395306110382));
    assert (close (boostedPeak.a2, 0.911675333976746));
    assert (close (high.b0, 0.613755762577057));
    assert (close (high.a1, -0.966220736503601));

    using namespace semantifx::eq::graph;
    assert (std::abs (frequencyToUnit (20.0)) < 1.0e-12);
    assert (std::abs (frequencyToUnit (20000.0) - 1.0) < 1.0e-12);
    assert (std::abs (unitToFrequency (frequencyToUnit (1000.0)) - 1000.0) < 1.0e-9);
    assert (std::abs (gainToUnit (24.0)) < 1.0e-12);
    assert (std::abs (unitToGain (gainToUnit (-6.0)) + 6.0) < 1.0e-12);

    std::array<Band, 6> graphBands {};
    for (auto& band : graphBands)
        band = { 0.0, 1000.0, 0.7071 };
    assert (std::abs (combinedMagnitudeDb (graphBands, 1000.0, sampleRate)) < 1.0e-8);
    graphBands[2] = { 6.0, 1000.0, 1.0 };
    assert (std::abs (combinedMagnitudeDb (graphBands, 1000.0, sampleRate) - 6.0) < 0.01);

    std::cout << "All Semantifx EQ math tests passed\n";
    {
        semantifx::dsp::EqEffect effect;
        effect.prepare (48000.0, 32);
        std::array<float, 32> block;
        block.fill (1.0f);
        float* channels[] { block.data() };
        effect.process (channels, 1, static_cast<int> (block.size()));
        for (const auto sample : block)
            assert (std::isfinite (sample));
    }
}
